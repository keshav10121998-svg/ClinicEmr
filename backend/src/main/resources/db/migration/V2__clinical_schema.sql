-- Visits (encounters), their signed versions, and the structured rows of the latest signed version.

CREATE TABLE encounter (
  id              UUID PRIMARY KEY,                    -- generated by the client so offline drafts can sync
  profile_id      BIGINT NOT NULL REFERENCES patient_profile(id),
  clinic_id       BIGINT NOT NULL REFERENCES clinic(id),
  doctor_id       BIGINT NOT NULL REFERENCES doctor(staff_id),
  visit_type      TEXT NOT NULL DEFAULT 'OPD' CHECK (visit_type IN ('OPD','FOLLOW_UP','EMERGENCY','TELE')),
  status          TEXT NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','SIGNED','CANCELLED')),
  draft           JSONB NOT NULL DEFAULT '{}',         -- working copy; after signing it holds the latest signed content
  draft_version   INT NOT NULL DEFAULT 0,              -- optimistic lock for autosave
  current_version INT NOT NULL DEFAULT 0,              -- 0 = never signed, 1 = first signature, 2+ = amendments
  started_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  signed_at       TIMESTAMPTZ,
  created_by      BIGINT NOT NULL REFERENCES staff_user(id),
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_enc_profile_time ON encounter(profile_id, started_at DESC) WHERE status = 'SIGNED';
CREATE INDEX ix_enc_clinic_day ON encounter(clinic_id, started_at);

-- Immutable record of every signature and amendment
CREATE TABLE encounter_version (
  encounter_id     UUID NOT NULL REFERENCES encounter(id),
  version          INT NOT NULL,
  snapshot         JSONB NOT NULL,
  content_hash     TEXT NOT NULL,                      -- SHA-256 of the canonical snapshot JSON
  signed_by        BIGINT NOT NULL REFERENCES doctor(staff_id),
  signed_at        TIMESTAMPTZ NOT NULL,
  amendment_reason TEXT,
  diff             JSONB,
  PRIMARY KEY (encounter_id, version)
);

CREATE TABLE encounter_note (
  encounter_id            UUID PRIMARY KEY REFERENCES encounter(id),
  chief_complaints        TEXT,
  history_present_illness TEXT,
  past_history            TEXT,
  examination             TEXT,
  advice                  TEXT,
  private_note            TEXT
);

CREATE TABLE vital_sign (
  id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  encounter_id UUID NOT NULL REFERENCES encounter(id),
  profile_id   BIGINT NOT NULL REFERENCES patient_profile(id),
  code         TEXT NOT NULL,                          -- LOINC
  display      TEXT NOT NULL,
  value        NUMERIC NOT NULL,
  unit         TEXT NOT NULL,                          -- UCUM
  observed_at  TIMESTAMPTZ NOT NULL
);
CREATE INDEX ix_vital_trend ON vital_sign(profile_id, code, observed_at DESC);

CREATE TABLE diagnosis (
  id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  encounter_id    UUID NOT NULL REFERENCES encounter(id),
  profile_id      BIGINT NOT NULL REFERENCES patient_profile(id),
  line_no         SMALLINT NOT NULL,
  code_system     TEXT CHECK (code_system IN ('ICD10','SNOMED')),
  code            TEXT,
  display         TEXT NOT NULL,
  kind            TEXT NOT NULL DEFAULT 'PRIMARY' CHECK (kind IN ('PRIMARY','SECONDARY','PROVISIONAL')),
  chronic         BOOLEAN NOT NULL DEFAULT false,
  UNIQUE (encounter_id, line_no)
);
CREATE INDEX ix_diagnosis_profile ON diagnosis(profile_id);

CREATE TABLE prescription (
  id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  encounter_id UUID NOT NULL UNIQUE REFERENCES encounter(id),
  profile_id   BIGINT NOT NULL REFERENCES patient_profile(id),
  printed_at   TIMESTAMPTZ
);

CREATE TABLE prescription_item (
  id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  prescription_id UUID NOT NULL REFERENCES prescription(id),
  line_no         SMALLINT NOT NULL,
  drug_id         BIGINT,
  drug_display    TEXT NOT NULL,
  generic_name    TEXT,
  dose            TEXT,
  frequency       TEXT NOT NULL,
  route           TEXT,
  timing          TEXT,
  duration_days   SMALLINT,
  long_term       BOOLEAN NOT NULL DEFAULT false,
  instructions    TEXT,
  UNIQUE (prescription_id, line_no)
);

CREATE TABLE investigation_order (
  id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  encounter_id UUID NOT NULL REFERENCES encounter(id),
  profile_id   BIGINT NOT NULL REFERENCES patient_profile(id),
  line_no      SMALLINT NOT NULL,
  code         TEXT,
  display      TEXT NOT NULL,
  status       TEXT NOT NULL DEFAULT 'ORDERED' CHECK (status IN ('ORDERED','RESULTED','CANCELLED')),
  UNIQUE (encounter_id, line_no)
);

CREATE TABLE follow_up (
  encounter_id     UUID PRIMARY KEY REFERENCES encounter(id),
  profile_id       BIGINT NOT NULL REFERENCES patient_profile(id),
  clinic_id        BIGINT NOT NULL REFERENCES clinic(id),
  due_date         DATE NOT NULL,
  note             TEXT,
  reminder_sent_at TIMESTAMPTZ,
  status           TEXT NOT NULL DEFAULT 'DUE' CHECK (status IN ('DUE','VISITED','MISSED','CANCELLED'))
);
CREATE INDEX ix_follow_up_due ON follow_up(clinic_id, due_date) WHERE status = 'DUE';

-- ===== terminology =====
CREATE TABLE icd10_code (
  code     TEXT PRIMARY KEY,
  display  TEXT NOT NULL,
  synonyms TEXT NOT NULL DEFAULT ''                    -- common local terms, space separated
);
CREATE INDEX ix_icd_search ON icd10_code USING gin ((display || ' ' || synonyms) gin_trgm_ops);

CREATE TABLE drug (
  id           BIGSERIAL PRIMARY KEY,
  brand_name   TEXT,
  generic_name TEXT NOT NULL,
  strength     TEXT,
  form         TEXT NOT NULL,                          -- tablet, capsule, syrup, injection, cream, drops, inhaler
  schedule     TEXT,                                   -- H, H1, X, OTC
  source       TEXT NOT NULL DEFAULT 'MASTER' CHECK (source IN ('MASTER','CLINIC_ADDED')),
  active       BOOLEAN NOT NULL DEFAULT true
);
CREATE INDEX ix_drug_search ON drug USING gin ((coalesce(brand_name, '') || ' ' || generic_name) gin_trgm_ops);
